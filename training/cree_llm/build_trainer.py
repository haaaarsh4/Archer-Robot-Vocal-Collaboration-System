def _preflight(args) -> int:
    print(f"python  {sys.version.split()[0]}  ({sys.platform})")
    missing: list[str] = []
    for module, spec in REQUIRED:
        try:
            print(f"  ok    {module:16s} {getattr(importlib.import_module(module), '__version__', '?')}")
        except Exception as exc:
            print(f"  MISS  {module:16s} {type(exc).__name__}: {exc}")
            missing.append(spec)

    try:
        import torch

        print(f"\\ntorch   {torch.__version__}  cuda={torch.version.cuda}")
        if torch.cuda.is_available():
            for i in range(torch.cuda.device_count()):
                props = torch.cuda.get_device_properties(i)
                print(f"gpu {i}   {props.name}  {props.total_memory / 1024 ** 3:.1f} GB")
            print(f"bf16    {torch.cuda.is_bf16_supported()}")
        else:
            print("gpu     none visible; set CUDA_VISIBLE_DEVICES, or training will crawl on CPU")
    except Exception as exc:
        print(f"\\ntorch could not be imported: {exc}")

    work = _work_dir(args)
    print(f"\\nwork    {work}")
    for label, path in (("work", work), ("hf", Path(args.hf_home).expanduser() if args.hf_home else work / "hf")):
        try:
            path.mkdir(parents=True, exist_ok=True)
            print(f"disk    {shutil.disk_usage(path).free / 1024 ** 3:8.1f} GB free  {label} {path}")
        except Exception as exc:
            print(f"disk    cannot use {path}: {exc}")

    if missing:
        print("\\nMissing packages. Install them, then run this again:\\n")
        print("  python -m pip install " + " ".join(f'"{spec}"' for spec in missing))
        return 1
    print("\\nall imports present. Run the same command without --check to start.")
    return 0


def _start_log(args):
    if args.no_log:
        return None
    path = (Path(args.log_file).expanduser() if args.log_file
            else _work_dir(args) / "logs" / f"train-{time.strftime('%Y%m%d-%H%M%S')}.log")
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        handle = path.open("a", encoding="utf-8", buffering=1)
    except OSError as exc:
        print(f"[warning] cannot write a log file at {path}: {exc}")
        return None
    sys.stdout = _Tee(getattr(sys, "__stdout__", None), handle)
    sys.stderr = _Tee(getattr(sys, "__stderr__", None), handle)
    return path


def _stop_after(name: str) -> bool:
    if ARGS.to != name:
        return False
    print(f"\\n[stop] reached --to {name}. Everything above is on disk; "
          f"re-run without --to to continue from here.", flush=True)
    return True


