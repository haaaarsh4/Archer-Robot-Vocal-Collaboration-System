class _Tee:
    """Write to the terminal and to a log file at the same time."""

    def __init__(self, *streams):
        self.streams = [s for s in streams if s is not None]

    def write(self, data):
        for stream in self.streams:
            stream.write(data)
            stream.flush()
        return len(data)

    def flush(self):
        for stream in self.streams:
            stream.flush()

    def isatty(self) -> bool:
        return False


def _work_dir(args) -> Path:
    raw = args.work or os.environ.get("CREE_WORK") or "cree_llm_work"
    return Path(raw).expanduser().resolve()


def _gpu_inventory() -> list[dict]:
    """Every card with its free memory, as nvidia-smi reports it.

    Read before torch is imported. A CUDA context allocates a few hundred
    megabytes on the default card, and torch cannot see another user's process
    at all; nvidia-smi can, which is the whole point here.
    """
    try:
        out = subprocess.run(
            ["nvidia-smi", "--query-gpu=index,name,memory.total,memory.free",
             "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=15,
        )
    except (OSError, subprocess.SubprocessError):
        return []
    if out.returncode != 0:
        return []
    cards: list[dict] = []
    for line in out.stdout.splitlines():
        parts = [part.strip() for part in line.split(",")]
        if len(parts) < 4:
            continue
        try:
            cards.append({
                "index": int(parts[0]),
                "name": parts[1],
                "total_mib": float(parts[2]),
                "free_mib": float(parts[3]),
            })
        except ValueError:
            continue
    return cards


# A 7B load in nf4 needs room for transformers' warmup allocation plus the
# quantised weights. Below this, the load itself is what fails.
GPU_LOAD_GB = 8.0


def _select_gpu(args) -> None:
    """Pin the run to a card that is actually free.

    CUDA defaults to device 0, and on a shared box device 0 is often busy. The
    failure then arrives from inside transformers as a five-gigabyte allocation
    during caching_allocator_warmup, which never mentions the other process.
    Choosing by free memory keeps the run alive; logging the choice makes it
    visible.
    """
    if args.gpu is not None:
        os.environ["CUDA_VISIBLE_DEVICES"] = str(args.gpu)
        print(f"gpu:     device {args.gpu} (from --gpu)", flush=True)
        return
    if os.environ.get("CUDA_VISIBLE_DEVICES"):
        print(f"gpu:     CUDA_VISIBLE_DEVICES={os.environ['CUDA_VISIBLE_DEVICES']} kept as set",
              flush=True)
        return
    cards = _gpu_inventory()
    if not cards:
        return
    best = max(cards, key=lambda card: card["free_mib"])
    note = ""
    if best["index"] != 0:
        os.environ["CUDA_VISIBLE_DEVICES"] = str(best["index"])
        note = f"device 0 has {cards[0]['free_mib'] / 1024:.1f} GB free; "
    print(f"gpu:     {note}using device {best['index']} {best['name']} "
          f"({best['free_mib'] / 1024:.1f} GB free)", flush=True)
    if best["free_mib"] / 1024 < GPU_LOAD_GB:
        print(f"gpu:     warning: only {best['free_mib'] / 1024:.1f} GB free and a "
              f"7B load needs about {GPU_LOAD_GB:.0f} GB. Free a card or pass --gpu N.",
              flush=True)


