def cells() -> list[Path]:
    return [p for p in sorted(CELLS.iterdir()) if p.suffix == ".py"]


def source_of(path: Path) -> str:
    """The cell as a script: Colab magics and the future import removed.

    `from __future__` is hoisted to the top of the generated file; leaving it
    inside a cell would be a SyntaxError there.
    """
    kept: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.lstrip()
        if stripped.startswith(("!", "%")):
            continue
        if stripped == "from __future__ import annotations":
            continue
        kept.append(line)
    return "\n".join(kept).rstrip()


def build() -> str:
    parts: list[str] = [HEADER.rstrip(), ""]
    for path in cells():
        parts.append("# " + "═" * 76)
        parts.append(f"# cell {path.stem}")
        parts.append("# " + "═" * 76)
        parts.append("")
        parts.append(source_of(path))
        parts.append("")
        gate = GATES.get(path.stem)
        if gate:
            parts.append(f"if _stop_after({gate!r}):")
            parts.append("    raise SystemExit(0)")
            parts.append("")
        if path.stem == "01_setup":
            parts.append("# Command line overrides, applied to the config the cell just built.")
            parts.append("_apply_overrides()")
            parts.append("")

    parts.extend([
        "# " + "═" * 76,
        "# done",
        "# " + "═" * 76,
        "",
        "print()",
        'print("=" * 78)',
        'log(f"pipeline finished in {(time.time() - STARTED) / 60:.1f} min")',
        'log(f"work dir   {ROOT}")',
        'log(f"benchmark  {OUT / \'creebench_report.json\'}")',
        'log(f"report     {OUT / \'report_card.md\'}")',
        'log(f"figures    {PLOTS}")',
        'log(f"export     {EXPORT}")',
        'print("=" * 78)',
        'print("re-run this command to refresh a stage, or --to STAGE to stop earlier")',
        "",
    ])
    return "\n".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rendered = build()
    try:
        compile(rendered, str(OUT), "exec")
    except SyntaxError as exc:
        print(f"generated file does not compile: {exc}", file=sys.stderr)
        return 1

    if args.check:
        if not OUT.exists():
            print(f"missing {OUT}", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != rendered:
            print(f"{OUT} is out of date; rerun build_trainer.py", file=sys.stderr)
            return 1
        print(f"{OUT.name} matches its cell sources")
        return 0

    OUT.write_text(rendered, encoding="utf-8")
    OUT.chmod(0o755)
    print(f"wrote {OUT} ({len(rendered.splitlines()):,} lines, {len(rendered) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
