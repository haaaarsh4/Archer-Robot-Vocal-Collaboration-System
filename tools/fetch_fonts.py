#!/usr/bin/env python3
"""Fetch the site's webfonts from Google Fonts and store them locally.

The site used to pull Space Grotesk / Space Mono off googleapis at page load.
The redesign serves its own fonts from frontend/fonts/ so the page renders
identically offline (it is a fully local instrument).

Only the latin + latin-ext subsets are kept, the page never shows anything
outside those ranges. Cree syllabics are handled by the system font
(Noto Sans Canadian Aboriginal) which is listed as a fallback in the CSS.

Usage:  .venv/bin/python tools/fetch_fonts.py
"""

from __future__ import annotations

import base64
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "frontend" / "fonts"

# Inter Tight is asked for on both axes. The italic is what the body copy's
# own emphasis is set in (`.prose em`): the serif italic that used to be there
# is a display face with a small x-height, and inside 19px paragraphs it read
# as a smudge rather than as emphasis.
CSS_URL = (
    "https://fonts.googleapis.com/css2"
    "?family=Inter+Tight:ital,wght@0,200..800;1,200..800"
    "&family=Cormorant+Garamond:ital,wght@0,400;0,500;0,600;1,400"
    "&family=Mr+De+Haviland"
    "&family=Space+Mono:wght@400;700"
    "&display=swap"
)

# Two families whose files are in this folder but which Google will not serve:
# Amita (free, but kept here by hand so the wordmark's face is pinned) and
# Clearface ITC (commercial, pulled off the reference site's own stylesheet).
# They are written after the fetched blocks, so regenerating this file does not
# quietly drop them.
EXTRA_CSS = """/* ==== Amita: the display face for the home page wordmark. Of every free face
   it is the closest to the reference's looped calligraphic capitals and
   single-storey lowercase (compared side by side with the reference frame at
   matched width, see the notes). =============================== */
@font-face {
  font-family: 'Amita';
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url(amita-400.woff2) format('woff2');
}

/* ==== Clearface ITC W01: the small-caps and caption face the reference site
   sets its captions in. Extracted from their own stylesheet so the captions
   are the same face; it is a commercial Linotype font, so if this project
   ever goes public, license it or swap the stack in --clearface. ==== */
@font-face {
  font-family: 'Clearface ITC';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url(clearface-400.woff) format('woff');
}
@font-face {
  font-family: 'Clearface ITC';
  font-style: normal;
  font-weight: 700;
  font-display: swap;
  src: url(clearface-700.woff) format('woff');
}
"""

UA = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"
)

BLOCK_RE = re.compile(r"/\*\s*([a-z0-9\-]+)\s*\*/\s*(@font-face\s*\{.*?\})", re.S)
KEEP_SUBSETS = {"latin", "latin-ext"}


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=40) as resp:
        return resp.read()


def slug(family: str, style: str, weight: str, subset: str) -> str:
    fam = re.sub(r"[^a-z0-9]+", "-", family.lower()).strip("-")
    return f"{fam}-{style}-{weight}-{subset}.woff2"


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    css = fetch(CSS_URL).decode("utf-8")

    blocks = BLOCK_RE.findall(css)
    if not blocks:
        print("no @font-face blocks found in the Google CSS", file=sys.stderr)
        return 1

    out_css: list[str] = [
        "/* Self-hosted webfonts for the Archer-Robot site.",
        "   Generated by tools/fetch_fonts.py, edit that script, not this file. */",
        "",
    ]
    downloaded = 0
    for subset, block in blocks:
        if subset not in KEEP_SUBSETS:
            continue
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        style = re.search(r"font-style:\s*([a-z]+)", block).group(1)
        weight = re.search(r"font-weight:\s*([0-9]+(?:\s+[0-9]+)?)", block).group(1)
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)

        name = slug(family, style, weight.split()[0], subset)
        target = OUT / name
        if not target.exists() or target.stat().st_size == 0:
            target.write_bytes(fetch(url))
            downloaded += 1

        # The signature is the first thing drawn on the page. A separate font
        # request, even a preloaded one, can lose the race against first paint
        # and leave a serif standing where the script belongs. So the latin
        # file is carried inside this stylesheet as a data URI: it is part of
        # the CSS the page is already waiting for, and there is no second
        # request that can arrive late. `block` keeps the fallback invisible
        # in the one case where the browser still has to decode it.
        inline_signature = family == "Mr De Haviland" and subset == "latin"
        if family == "Mr De Haviland":
            block = block.replace("font-display: swap", "font-display: block")

        if inline_signature:
            data = base64.b64encode(target.read_bytes()).decode("ascii")
            local = re.sub(
                r"url\(https://[^)]+\.woff2\)",
                f"url(data:font/woff2;base64,{data})",
                block,
            )
            out_css.append("/* the signature face, inline so first paint already has it */")
        else:
            local = re.sub(
                r"url\(https://[^)]+\.woff2\)",
                f"url({name})",
                block,
            )
            out_css.append(f"/* {subset} */")
        out_css.append(local)
        out_css.append("")

    out_css.append(EXTRA_CSS)
    (OUT / "fonts.css").write_text("\n".join(out_css), encoding="utf-8")
    files = sorted(p.name for p in OUT.glob("*.woff2"))
    total_kb = sum((OUT / f).stat().st_size for f in files) / 1024
    print(f"wrote {OUT / 'fonts.css'}")
    print(f"{len(files)} woff2 files, {downloaded} newly downloaded, {total_kb:.0f} KB total")
    for f in files:
        print("  ", f)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
